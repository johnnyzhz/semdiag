function generate_tangent(nodes, edge) {
    var tangent = null;
    if (edge.power === 2) tangent = generate_tangent_bcurve2p(nodes, edge);
    else if (edge.power === 3) tangent = generate_tangent_bcurve3p(nodes, edge);
    return tangent;
}

function generate_tangents(nodes, edges) {
    var tangents = [];
    for (var i = 0; i < edges.length; i++) {
        var tangent = null;
        tangent = generate_tangent(nodes, edges[i]);
        tangents.push(tangent);
    }
    return tangents;
}

function generate_new_handleP_for_movednode(nodes, edge, pointType, newPos) {
    function segmentLength(seg) {
        return Math.sqrt((seg.P2.x - seg.P1.x) * (seg.P2.x - seg.P1.x) + (seg.P2.y - seg.P1.y) * (seg.P2.y - seg.P1.y));
    }
    var newHandleP = edge.handleP,
        startIndex = matchnodeindex(nodes, edge.startid),
        endIndex = matchnodeindex(nodes, edge.endid),
        startCenter = {
            x: nodes[startIndex].x,
            y: nodes[startIndex].y
        },
        endCenter = {
            x: nodes[endIndex].x,
            y: nodes[endIndex].y
        },
        handleP = edge.handleP,
        angles;
    if (pointType === "endP") angles = calculate_angles_of_triangle(startCenter, handleP, newPos);
    else angles = calculate_angles_of_triangle(newPos, handleP, endCenter);
    if (angles.Is_success) {
        var angleP0 = angles.angle_P0,
            angleP2 = angles.angle_P2,
            anticlockwise = angles.angle_anticlockwise;
        if (pointType === "startP") {
            var newToHandle = {
                    P1: newPos,
                    P2: handleP
                },
                newToHandleLen = segmentLength(newToHandle),
                newToEnd = {
                    P1: newPos,
                    P2: endCenter
                },
                newToEndLen = segmentLength(newToEnd),
                startToEnd = {
                    P1: startCenter,
                    P2: endCenter
                },
                startToEndLen = segmentLength(startToEnd),
                scaleStart = newToHandleLen * startToEndLen / newToEndLen,
                baseAngleStart = Math.acos((startToEnd.P2.x - startToEnd.P1.x) / startToEndLen),
                startToEndAngle = startToEnd.P2.y >= startToEnd.P1.y ? baseAngleStart : 2 * Math.PI - baseAngleStart,
                rotatedAngleStart = anticlockwise ? startToEndAngle + angleP0 : startToEndAngle - angleP0;
            newHandleP = {
                x: startToEnd.P1.x + scaleStart * Math.cos(rotatedAngleStart),
                y: startToEnd.P1.y + scaleStart * Math.sin(rotatedAngleStart)
            };
        } else if (pointType === "endP") {
            var newToHandleE = {
                    P1: newPos,
                    P2: handleP
                },
                newToHandleELen = segmentLength(newToHandleE),
                newToStart = {
                    P1: newPos,
                    P2: startCenter
                },
                newToStartLen = segmentLength(newToStart),
                endToStart = {
                    P1: endCenter,
                    P2: startCenter
                },
                endToStartLen = segmentLength(endToStart),
                scaleEnd = newToHandleELen * endToStartLen / newToStartLen,
                baseAngleEnd = Math.acos((endToStart.P2.x - endToStart.P1.x) / endToStartLen),
                endToStartAngle = endToStart.P2.y >= endToStart.P1.y ? baseAngleEnd : 2 * Math.PI - baseAngleEnd,
                rotatedAngleEnd = anticlockwise ? endToStartAngle - angleP2 : endToStartAngle + angleP2;
            newHandleP = {
                x: endToStart.P1.x + scaleEnd * Math.cos(rotatedAngleEnd),
                y: endToStart.P1.y + scaleEnd * Math.sin(rotatedAngleEnd)
            };
        }
    }
    return newHandleP;
}
