function generate_resize_cPs(nodes) {
    var handles = [];
    for (var i = 0; i < nodes.length; i++) {
        var node = nodes[i],
            rx = node.rx,
            ry = node.ry;
        switch (node.type) {
            case "ellipse":
            case "rect":
                var leftP = {
                        x: node.x - rx - 2 * cPr,
                        y: node.y
                    },
                    rightP = {
                        x: node.x + rx + 2 * cPr,
                        y: node.y
                    },
                    topP = {
                        x: node.x,
                        y: node.y - ry - 2 * cPr
                    },
                    bottomP = {
                        x: node.x,
                        y: node.y + ry + 2 * cPr
                    };
                handles.push({
                    nodeid: node.id,
                    pos: leftP,
                    type: "left"
                });
                handles.push({
                    nodeid: node.id,
                    pos: rightP,
                    type: "right"
                });
                handles.push({
                    nodeid: node.id,
                    pos: topP,
                    type: "top"
                });
                handles.push({
                    nodeid: node.id,
                    pos: bottomP,
                    type: "bottom"
                });
                break;
            case "triangle":
                var triangleTopP = {
                        x: node.x,
                        y: node.y - ry - 2 * cPr
                    },
                    leftBottomP = {
                        x: node.x - rx * Math.sqrt(3) / 2 - 2 * cPr,
                        y: node.y + ry / 2 + 2 * cPr
                    },
                    rightBottomP = {
                        x: node.x + rx * Math.sqrt(3) / 2 + 2 * cPr,
                        y: node.y + ry / 2 + 2 * cPr
                    };
                handles.push({
                    nodeid: node.id,
                    pos: triangleTopP,
                    type: "top"
                });
                handles.push({
                    nodeid: node.id,
                    pos: leftBottomP,
                    type: "left_bottom"
                });
                handles.push({
                    nodeid: node.id,
                    pos: rightBottomP,
                    type: "right_bottom"
                });
        }
    }
    return handles;
}

