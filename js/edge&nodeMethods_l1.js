function cal_labelP(anchorP, startP, endP, power, offsetX, offsetY) {
    var labelP = {
        x: anchorP.x + 15,
        y: anchorP.y - 15
    };
    switch (power) {
        case 2:
            labelP = offsetX !== null && offsetY !== null ? {
                x: anchorP.x + offsetX,
                y: anchorP.y + offsetY
            } : {
                x: anchorP.x + 15,
                y: anchorP.y - 15
            };
            break;
        case 3:
            if (anchorP.x < startP.x) labelP.x = anchorP.x - 20;
            else if (anchorP.x > startP.x) labelP.x = anchorP.x + 15;
            else labelP.x = anchorP.x;
            if (anchorP.y < startP.y) labelP.y = anchorP.y - 15;
            else if (anchorP.y > startP.y) labelP.y = anchorP.y + 20;
            else labelP.y = anchorP.y;
    }
    return labelP;
}

