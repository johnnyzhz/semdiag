/* Distance from a self-loop anchor to the boundary of an ellipse along direction theta. */
function ellipseBoundaryDistance(node, theta) {
    var rx = node.rx,
        ry = node.ry;
    return rx * ry / Math.sqrt(ry * Math.cos(theta) * (ry * Math.cos(theta)) + rx * Math.sin(theta) * (rx * Math.sin(theta)));
}

/* Distance from a self-loop anchor to the boundary of a rectangle along direction theta. */
function rectBoundaryDistance(node, theta) {
    var rx = node.rx,
        ry = node.ry,
        cornerAngle = Math.atan(ry / rx),
        distance = 0;
    if (theta >= cornerAngle & theta <= Math.PI - cornerAngle) distance = Math.abs(ry / Math.sin(theta));
    else if (theta >= 2 * Math.PI - cornerAngle & theta <= 2 * Math.PI || theta >= 0 & theta <= cornerAngle) distance = Math.abs(rx / Math.cos(theta));
    else if (theta >= Math.PI + cornerAngle & theta <= 2 * Math.PI - cornerAngle) distance = Math.abs(ry / Math.sin(theta));
    else if (theta >= Math.PI - cornerAngle & theta <= Math.PI + cornerAngle) distance = Math.abs(rx / Math.cos(theta));
    return distance;
}

function generate_bcurve3p(nodes, nodeId, curveType) {
    var selfTheta = selfpathTHETA_default,
        selfAngle = selfpathANGLE_default,
        nodeIndex = matchnodeindex(nodes, nodeId),
        node = nodes[nodeIndex],
        curveLR = default_selfcurve_LR,
        boundaryDistance = 0,
        offset = 0;
    switch (node.type) {
        case "ellipse":
            boundaryDistance = ellipseBoundaryDistance(node, selfTheta);
            break;
        case "rect":
            boundaryDistance = rectBoundaryDistance(node, selfTheta);
            break;
        case "triangle":
            var bottomLeftP = {
                    x: node.x - node.rx * Math.sqrt(3) / 2,
                    y: node.y + node.rx / 2
                },
                bottomRightP = {
                    x: node.x + node.rx * Math.sqrt(3) / 2,
                    y: node.y + node.rx / 2
                },
                topP = {
                    x: node.x,
                    y: node.y - node.ry
                },
                baseSeg = {
                    P1: bottomLeftP,
                    P2: bottomRightP
                },
                rightSeg = {
                    P1: topP,
                    P2: bottomRightP
                },
                leftSeg = {
                    P1: bottomLeftP,
                    P2: topP
                },
                baseSlope = (baseSeg.P2.y - baseSeg.P1.y) / (baseSeg.P2.x - baseSeg.P1.x),
                rightSlope = (rightSeg.P2.y - rightSeg.P1.y) / (rightSeg.P2.x - rightSeg.P1.x),
                leftSlope = (leftSeg.P2.y - leftSeg.P1.y) / (leftSeg.P2.x - leftSeg.P1.x),
                baseLine = {
                    A: baseSlope,
                    B: -1,
                    C: baseSeg.P1.y - baseSlope * baseSeg.P1.x
                },
                rightLine = {
                    A: rightSlope,
                    B: -1,
                    C: rightSeg.P1.y - rightSlope * rightSeg.P1.x
                },
                leftLine = {
                    A: leftSlope,
                    B: -1,
                    C: leftSeg.P1.y - leftSlope * leftSeg.P1.x
                };
            var rayLine;
            if (selfTheta % (Math.PI / 2) === 0) rayLine = {
                A: 1,
                B: 0,
                C: node.x
            };
            else rayLine = {
                A: Math.tan(selfTheta),
                B: -1,
                C: node.y - Math.tan(selfTheta) * node.x
            };
            var hit = {};
            if (selfTheta >= Math.PI / 6 & selfTheta <= 5 * Math.PI / 6) hit = interP_2lines(baseLine.A, baseLine.B, baseLine.C, rayLine.A, rayLine.B, rayLine.C);
            else if (selfTheta >= 3 * Math.PI / 2 & selfTheta <= 2 * Math.PI || selfTheta >= 0 & selfTheta <= 1 * Math.PI / 6) hit = interP_2lines(rightLine.A, rightLine.B, rightLine.C, rayLine.A, rayLine.B, rayLine.C);
            else if (selfTheta >= 5 * Math.PI / 6 & selfTheta <= 3 * Math.PI / 2) hit = interP_2lines(leftLine.A, leftLine.B, leftLine.C, rayLine.A, rayLine.B, rayLine.C);
            if (1 === hit.numsolution) boundaryDistance = Math.sqrt((hit.interP.x - node.x) * (hit.interP.x - node.x) + (hit.interP.y - node.y) * (hit.interP.y - node.y));
    }
    offset = boundaryDistance - default_RADIUSH * newr_DISCOUNT;
    var tipX = node.x + offset * Math.cos(selfTheta),
        tipY = node.y + offset * Math.sin(selfTheta),
        tipP = {
            x: tipX,
            y: tipY
        },
        ctrl1P = {
            x: tipX + curveLR * Math.cos(selfTheta + selfAngle),
            y: tipY + curveLR * Math.sin(selfTheta + selfAngle)
        },
        ctrl2P = {
            x: tipX + curveLR * Math.cos(selfTheta - selfAngle),
            y: tipY + curveLR * Math.sin(selfTheta - selfAngle)
        },
        handleP = {
            x: 1 * tipP.x / 8 + 3 * ctrl1P.x * 1 / 8 + 3 * ctrl2P.x * 1 / 8 + 1 * tipP.x / 8,
            y: 1 * tipP.y / 8 + 3 * ctrl1P.y * 1 / 8 + 3 * ctrl2P.y * 1 / 8 + 1 * tipP.y / 8
        },
        line = "M" + tipP.x + " " + tipP.y + " C" + ctrl1P.x + " " + ctrl1P.y + " " + ctrl2P.x + " " + ctrl2P.y + " " + tipP.x + " " + tipP.y,
        label = generate_label(node, node, curveType, 3),
        center = {
            x: node.x,
            y: node.y
        },
        labelP = cal_labelP(handleP, center, center, 3, null, null);
    return {
        id: "edge" + String(Edgecurrent_IdNUM),
        power: 3,
        nodeid: nodeId,
        startid: nodeId,
        endid: nodeId,
        theta: selfTheta,
        handleP: handleP,
        P0: tipP,
        P1: ctrl1P,
        P2: ctrl2P,
        P3: tipP,
        line: line,
        type: curveType,
        dotted: 0,
        color: defaultCOLOR,
        strokewidth: default_strokeWIDTH,
        label: label,
        labelP: labelP,
        labelFsize: defaultFONTSIZE,
        labelInitial: true,
        labelshow: true,
        curve_LR: curveLR,
        handlePshow: false,
        handleInitial: true,
        IsAutoGenerated: false,
        selected: false
    };
}

