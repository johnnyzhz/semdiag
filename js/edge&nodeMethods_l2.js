function texteditdialog(kind, target) {
    var originalText;
    switch (kind) {
        case "node":
            originalText = target.title;
            break;
        case "edge":
            originalText = target.label;
            break;
        case "note":
            originalText = target.text;
    }

    $("#edittextdialog").remove();

    var dialogDiv = document.createElement("div");
    dialogDiv.id = "edittextdialog";
    dialogDiv.style.color = "black";

    var contentDiv = document.createElement("div");
    contentDiv.style = "width=230px; height=100px";

    var form = document.createElement("form");
    form.id = "texteditform";

    var textInput = document.createElement("input");
    textInput.id = "edittextinput";
    textInput.type = "text";
    textInput.name = "text";
    textInput.style = "width=200px; height=50px";
    textInput.contentEditable = true;
    textInput.value = originalText;
    textInput.focus();

    var okButton = document.createElement("button");
    okButton.innerHTML = "OK";
    okButton.id = "dialogbuton1";

    $(textInput).keydown(function (event) {
        if (event.keyCode === 13) {
            event.preventDefault();
            $(okButton).click();
            return false;
        }
    });

    form.appendChild(textInput);
    contentDiv.appendChild(form);

    $(okButton).click(function () {
        if (originalText != textInput.value) {
            switch (kind) {
                case "node":
                    target.title = textInput.value;
                    var minimumRx = target.title.length * target.fontsize * 0.5;
                    if (target.rx <= minimumRx) {
                        target.rx = minimumRx;
                        var relatedIndexes = lookfor_relatededges(target.id);
                        for (var j = 0; j < relatedIndexes.length; j++) {
                            var edgeIndex = relatedIndexes[j];
                            if (edges[edgeIndex].power === 2) {
                                edges[edgeIndex] = update_bcurve2p(nodes, edges[edgeIndex]);
                            } else if (edges[edgeIndex].power === 3) {
                                edges[edgeIndex] = update_bcurve3p(nodes, edges[edgeIndex], edges[edgeIndex].theta, selfpathANGLE_default);
                            }
                            edges_tangents[edgeIndex] = generate_tangent(nodes, edges[edgeIndex]);
                        }
                    }
                    break;
                case "edge":
                    target.label = textInput.value;
                    target.labelInitial = false;
                    break;
                case "note":
                    target.text = textInput.value;
            }
        }
        $(dialogDiv).dialog("close");
        $("#edittextdialog").remove();
        updatesvg();
    });
    contentDiv.appendChild(okButton);

    var cancelButton = document.createElement("button");
    cancelButton.innerHTML = "Cancel";
    cancelButton.id = "dialogbuton2";
    $(cancelButton).click(function () {
        $(dialogDiv).dialog("close");
        $("#edittextdialog").remove();
    });
    contentDiv.appendChild(cancelButton);

    dialogDiv.appendChild(contentDiv);
    $(dialogDiv).dialog({
        modal: true,
        title: "Edit Text",
        width: "230",
        height: "130",
        bgiframe: true,
        closeOnEscape: true,
        draggable: true,
        resizable: true
    });
}

// Returns the bounding box {x1, y1, x2, y2} of a node, edge, or note.
function Cal_Boundary(item, kind) {
    var bounds = { x1: 0, y1: 0, x2: 0, y2: 0 };
    switch (kind) {
        case "node":
            bounds.x1 = item.x - item.rx;
            bounds.y1 = item.y - item.ry;
            bounds.x2 = item.x + item.rx;
            bounds.y2 = item.y + item.ry;
            break;
        case "edge":
            var startNode = nodes[matchnodeindex(nodes, item.startid)];
            var endNode = nodes[matchnodeindex(nodes, item.endid)];
            var handle = item.handleP;
            bounds.x1 = Math.min(startNode.x, endNode.x, handle.x);
            bounds.y1 = Math.min(startNode.y, endNode.y, handle.y);
            bounds.x2 = Math.max(startNode.x, endNode.x, handle.x);
            bounds.y2 = Math.max(startNode.y, endNode.y, handle.y);
            break;
        case "note":
            var halfWidth = item.text.length * item.fontsize * 0.5;
            var halfHeight = item.fontsize;
            bounds.x1 = item.x - halfWidth;
            bounds.y1 = item.y - halfHeight;
            bounds.x2 = item.x + halfWidth;
            bounds.y2 = item.y + halfHeight;
    }
    return bounds;
}
