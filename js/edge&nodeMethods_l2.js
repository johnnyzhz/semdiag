function findIndexes(array, value) {
    var indexes = [];
    for (var i = 0; i < array.length; i++) {
        if (array[i] === value) indexes.push(i);
    }
    return indexes;
}

function node_add(position, rx, ry, type) {
    var node = null;
    var titlePrefix = "V";
    Nodecurrent_IdNUM++;
    var nodeId = "node" + String(Nodecurrent_IdNUM);
    switch (type) {
        case "rect":
            node = NewNode();
            node.type = type;
            titlePrefix = "X";
            Rec_current_TitleNUM++;
            node.title = titlePrefix + Rec_current_TitleNUM;
            nodes.push(node);
            numRec++;
            numNode++;
            break;
        case "ellipse":
            node = NewNode();
            node.type = type;
            titlePrefix = "F";
            Elli_current_TitleNUM++;
            node.title = titlePrefix + Elli_current_TitleNUM;
            nodes.push(node);
            numElli++;
            numNode++;
            break;
        case "triangle":
            node = NewNode();
            node.type = type;
            node.title = "1";
            nodes.push(node);
            numTri++;
            numNode++;
    }
    node.id = nodeId;
    node.x = position.x;
    node.y = position.y;
    node.rx = rx;
    node.ry = ry;
    return node;
}

function node_delete(nodeIndex) {
    var node = nodes[nodeIndex];
    var cleaned = delete_relatededges(node, edges, edges_tangents);
    edges = cleaned.edges;
    edges_tangents = cleaned.edges_tangents;
    if (matchnodeindex(nodes, node.id) >= 0 && matchnodeindex(nodes, node.id) < nodes.length) {
        switch (node.type) {
            case "ellipse":
                numElli--;
                numNode--;
                break;
            case "rect":
                numRec--;
                numNode--;
                break;
            case "triangle":
                numTri--;
                numNode--;
        }
        nodes.splice(nodeIndex, 1);
    }
}

function node_copy(node) {
    if (node === null) return null;
    var copy = node_add({ x: node.x, y: node.y }, node.rx, node.ry, node.type);
    copy.dotted = node.dotted;
    copy.color = node.color;
    copy.title = node.title;
    copy.fontsize = node.fontsize;
    copy.strokewidth = node.strokewidth;
    copy.selected = node.selected;
    copy.level = node.level;
    return copy;
}

// Deletes every power-2 edge from fromId to toId with the given type.
// Deleting shifts later entries left, and the loop does not step back, so
// the entry after each deletion is skipped. This matches the original code.
function deleteEdgesBetween(fromId, toId, curveType) {
    var deletedCount = 0;
    for (var i = 0; i < edges.length; i++) {
        if (edges[i].power === 2 && edges[i].startid === fromId && edges[i].endid === toId && edges[i].type === curveType) {
            edge_delete(i);
            deletedCount++;
        }
    }
    return deletedCount;
}

function delete_nonuseedges(startId, endId, curveType) {
    var deletedCount = 0;
    switch (curveType) {
        case "uni":
            if (deleteEdgesBetween(startId, endId, "bi") === 0) {
                deleteEdgesBetween(endId, startId, "bi");
            }
            break;
        case "bi":
            deletedCount += deleteEdgesBetween(startId, endId, "uni");
            deletedCount += deleteEdgesBetween(endId, startId, "uni");
            var endNode = nodes[matchnodeindex(nodes, endId)];
            var isDependent = Is_dependentnode(endNode, nodes, edges);
            if (!isDependent) {
                var duplicateIndex = lookfor_duplicatedbcurve(nodes, edges, endId, endId, "bi");
                if (duplicateIndex >= 0 && duplicateIndex < edges.length && 1 == edges[duplicateIndex].IsAutoGenerated) {
                    edge_delete(duplicateIndex);
                }
            }
    }
    return deletedCount;
}

function lookfor_relatededges(nodeId) {
    var relatedIndexes = [];
    for (var i = 0; i < edges.length; i++) {
        if (edges[i].power === 2) {
            if (nodeId === edges[i].startid) relatedIndexes.push(i);
            if (nodeId === edges[i].endid) relatedIndexes.push(i);
        } else if (edges[i].power === 3 && nodeId === edges[i].nodeid) {
            relatedIndexes.push(i);
        }
    }
    return relatedIndexes;
}

function edge_delete(edgeIndex) {
    var edge = edges[edgeIndex];
    if (edge.power === 2 && edge.type === "uni") {
        var startNode = nodes[matchnodeindex(nodes, edge.startid)];
        var endNode = nodes[matchnodeindex(nodes, edge.endid)];
        edges.splice(edgeIndex, 1);
        edges_tangents.splice(edgeIndex, 1);
        var endNodeIsDependent = Is_dependentnode(endNode, nodes, edges);
        if (!endNodeIsDependent) {
            var duplicateIndex = lookfor_duplicatedbcurve(nodes, edges, endNode.id, endNode.id, "bi");
            if (duplicateIndex >= 0 && duplicateIndex < edges.length && edges[duplicateIndex].IsAutoGenerated === true) {
                edges.splice(duplicateIndex, 1);
                edges_tangents.splice(duplicateIndex, 1);
            }
        }
        if (startNode.type === "triangle") {
            var startNodeStillUsed = edges.some(function (candidate) {
                return candidate.power === 2 && candidate.startid === startNode.id;
            });
            if (!startNodeStillUsed) {
                node_delete(matchnodeindex(nodes, startNode.id));
            }
        }
    } else {
        edges.splice(edgeIndex, 1);
        edges_tangents.splice(edgeIndex, 1);
    }
    return true;
}

function delete_relatededges(node, edgeList, tangentList) {
    var nodeId = node.id;
    for (var i = 0; i < edgeList.length; i++) {
        var touchesNode = false;
        if (edgeList[i].power === 2) {
            touchesNode = edgeList[i].startid === nodeId || edgeList[i].endid === nodeId;
        } else if (edgeList[i].power === 3) {
            touchesNode = edgeList[i].nodeid === nodeId;
        }
        if (touchesNode && edge_delete(i)) {
            i--;
        }
    }
    return { edges: edgeList, edges_tangents: tangentList };
}

function edge_add_newbcurve(newEdge) {
    var newIndex = -1;
    var duplicateIndex, tangent;
    switch (newEdge.power) {
        case 2:
            duplicateIndex = lookfor_duplicatedbcurve(nodes, edges, newEdge.startid, newEdge.endid, newEdge.type);
            if (!(duplicateIndex >= 0 && duplicateIndex < edges.length)) {
                if (newEdge.type === "uni" || newEdge.type === "bi") {
                    delete_nonuseedges(newEdge.startid, newEdge.endid, newEdge.type);
                    edges.push(newEdge);
                    numEdge++;
                    Edgecurrent_IdNUM++;
                    tangent = generate_tangent(nodes, newEdge);
                    edges_tangents.push(tangent);
                    newIndex = numEdge - 1;
                }
            }
            break;
        case 3:
            duplicateIndex = lookfor_duplicatedbcurve(nodes, edges, newEdge.nodeid, newEdge.nodeid, newEdge.type);
            if (!(duplicateIndex >= 0 && duplicateIndex < edges.length)) {
                edges.push(newEdge);
                numEdge++;
                Edgecurrent_IdNUM++;
                tangent = generate_tangent(nodes, newEdge);
                edges_tangents.push(tangent);
                newIndex = numEdge - 1;
            }
    }
    return newIndex;
}

function edge_add(startIndex, endIndex, curveType) {
    var newIndex = -1;
    var edge, autoEdge;
    if (curveType === "uni") {
        if (startIndex != endIndex && nodes[endIndex].type !== "triangle") {
            edge = generate_edge(nodes, nodes[startIndex].id, nodes[endIndex].id, curveType);
            newIndex = edge_add_newbcurve(edge);
            if (nodes[startIndex].type !== "triangle") {
                autoEdge = generate_bcurve3p(nodes, nodes[endIndex].id, "bi");
                autoEdge.IsAutoGenerated = true;
                edge_add_newbcurve(autoEdge);
            }
        }
    } else if (curveType === "bi") {
        var touchesTriangle = (nodes[endIndex].type === "triangle" && endIndex != startIndex) ||
            (nodes[startIndex].type === "triangle" && endIndex != startIndex);
        if (!touchesTriangle) {
            edge = generate_edge(nodes, nodes[startIndex].id, nodes[endIndex].id, curveType);
            newIndex = edge_add_newbcurve(edge);
        }
    }
    return newIndex;
}

function note_add(position, text) {
    Notecurrent_IdNUM++;
    var note = NewNote();
    note.id = "note" + Notecurrent_IdNUM;
    note.x = position.x;
    note.y = position.y;
    note.text = text;
    notes.push(note);
    numnote++;
    return note;
}

function note_delete(noteIndex) {
    if (noteIndex >= 0 && noteIndex < notes.length) {
        notes.splice(noteIndex, 1);
        numnote--;
    }
}

